/** Hand-drawn sun from the About page — draws itself in, rays spin on hover. */
export function Sun({ className }: { className?: string }) {
  const reduce = useReducedMotion();
  const [hover, setHover] = useState(false);
  const draw = (i: number) => ({
    initial: reduce ? false : ({ pathLength: 0 } as const),
    whileInView: { pathLength: 1 },
    viewport: { once: true },
    transition: { duration: 0.5, delay: 0.1 + i * 0.07, ease: [0.65, 0, 0.35, 1] as const },
  });
  return (
    <svg
      viewBox="0 0 202 202"
      fill="none"
      className={className}
      onMouseEnter={() => setHover(true)}
      onMouseLeave={() => setHover(false)}
      aria-hidden
    >
      <motion.g
        style={{ transformOrigin: "101px 101px" }}
        animate={{ rotate: hover ? 35 : 0 }}
        transition={{ type: "spring", stiffness: 120, damping: 10 }}
      >
        {RAYS.map((d, i) => (
          <motion.path key={d} d={d} stroke="#FF0F0F" strokeWidth={3} strokeLinecap="round" {...draw(FACE.length + i)} />
        ))}
      </motion.g>
      <motion.g
        style={{ transformOrigin: "101px 98px" }}
        animate={{ rotate: hover ? -8 : 0, scale: hover ? 1.06 : 1 }}
        transition={{ type: "spring", stiffness: 200, damping: 12 }}
      >
        {FACE.map((d, i) => (
          <motion.path key={d} d={d} stroke="#FF0F0F" strokeWidth={3} strokeLinecap="round" {...draw(i)} />
        ))}
      </motion.g>
    </svg>
  );
}
