const RED = "#FF0F0F";
const EASE = [0.65, 0, 0.35, 1] as const;

/**
 * Hand-drawn sun from the About page. Draws itself in on scroll; on hover the
 * rays spin, the eyes and smile rub out and a pair of scribbled sunglasses
 * drops onto the face with a big toothy grin (Figma 1380:44712).
 */
export function Sun({ className }: { className?: string }) {
  const reduce = useReducedMotion();
  const [hover, setHover] = useState(false);
  const [drawn, setDrawn] = useState(false);

  const intro = (i: number) => ({
    initial: reduce ? false : ({ pathLength: 0 } as const),
    whileInView: { pathLength: 1 },
    viewport: { once: true },
    transition: { duration: 0.5, delay: 0.1 + i * 0.07, ease: EASE },
  });

  // Swap animations: features out fast, glasses + grin draw in one after another.
  const swap = (on: boolean, i: number, n: number) => ({
    pathLength: on ? 1 : 0,
    opacity: on ? 1 : 0,
    transition: {
      pathLength: { duration: reduce ? 0 : 0.35, ease: EASE, delay: reduce ? 0 : on ? 0.12 + i * 0.07 : (n - 1 - i) * 0.03 },
      opacity: { duration: 0.01, delay: on ? (reduce ? 0 : 0.12 + i * 0.07) : reduce ? 0 : 0.3 },
    },
  });

  return (
    <svg
      viewBox="0 0 202 202"
      fill="none"
      className={className}
      onMouseEnter={() => setHover(true)}
      onMouseLeave={() => setHover(false)}
      onClick={() => setHover((h) => !h)}
      aria-hidden
    >
      <motion.g
        style={{ transformOrigin: "101px 101px" }}
        animate={{ rotate: hover ? 35 : 0 }}
        transition={{ type: "spring", stiffness: 120, damping: 10 }}
      >
        {RAYS.map((d, i) => (
          <motion.path key={d} d={d} stroke={RED} strokeWidth={3} strokeLinecap="round" {...intro(FACE_ALL.length + i)} />
        ))}
      </motion.g>

      <motion.g
        style={{ transformOrigin: "101px 98px" }}
        animate={{ rotate: hover ? -6 : 0, scale: hover ? 1.06 : 1 }}
        transition={{ type: "spring", stiffness: 200, damping: 12 }}
      >
        <motion.path d={OUTLINE} stroke={RED} strokeWidth={3} strokeLinecap="round" {...intro(0)} onAnimationComplete={() => setDrawn(true)} />

        {/* Default face: eyes, brows and smile */}
        {FEATURES.map((d, i) =>
          drawn || reduce ? (
            <motion.path key={d} d={d} stroke={RED} strokeWidth={3} strokeLinecap="round" initial={false} animate={swap(!hover, i, FEATURES.length)} />
          ) : (
            <motion.path key={d} d={d} stroke={RED} strokeWidth={3} strokeLinecap="round" {...intro(i + 1)} />
          )
        )}

        {/* Cool face: sunglasses slide down a touch as they're drawn, then the grin */}
        <motion.g
          initial={false}
          animate={{ y: hover ? 0 : -6 }}
          transition={{ type: "spring", stiffness: 260, damping: 14, delay: hover ? 0.1 : 0 }}
        >
          {GLASSES.map((d, i) => (
            <motion.path
              key={d}
              d={d}
              stroke={RED}
              strokeWidth={3}
              strokeLinecap="round"
              strokeLinejoin="round"
              initial={{ pathLength: 0, opacity: 0 }}
              animate={swap(hover, i, GLASSES.length)}
            />
          ))}
        </motion.g>
        {GRIN.map(({ d, w }, i) => (
          <motion.path
            key={d}
            d={d}
            stroke={RED}
            strokeWidth={w}
            strokeLinecap="round"
            strokeLinejoin="round"
            initial={{ pathLength: 0, opacity: 0 }}
            animate={swap(hover, GLASSES.length + i, GLASSES.length + GRIN.length)}
          />
        ))}
      </motion.g>
    </svg>
  );
}
