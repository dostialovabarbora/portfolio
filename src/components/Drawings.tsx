"use client";
import { motion, useReducedMotion } from "motion/react";

/**
 * Hand-drawn strokes from the Figma file. Each path draws itself in
 * (path length 0 → 1, ease-out), matching the Figma stroke animation.
 */
type Stroke = { d: string; w: number };

function Drawing({
  viewBox,
  strokes,
  className,
  style,
  duration = 1.5,
  delay = 0,
  trigger = "view",
}: {
  viewBox: string;
  strokes: Stroke[];
  className?: string;
  style?: React.CSSProperties;
  duration?: number;
  delay?: number;
  /** "view" draws once when scrolled into view, "mount" draws on mount (use a key to replay). */
  trigger?: "view" | "mount";
}) {
  const reduce = useReducedMotion();
  const each = duration / strokes.length;
  return (
    <svg viewBox={viewBox} fill="none" aria-hidden className={className} style={style}>
      {strokes.map((s, i) => {
        const anim = { pathLength: 1, opacity: 1 };
        const transition = { pathLength: { duration: each, delay: delay + i * each * 0.9, ease: [0.16, 1, 0.3, 1] as const }, opacity: { duration: 0.01, delay: delay + i * each * 0.9 } };
        return (
          <motion.path
            key={i}
            d={s.d}
            stroke="currentColor"
            strokeWidth={s.w}
            strokeLinecap="round"
            strokeLinejoin="round"
            initial={reduce ? false : { pathLength: 0, opacity: 0 }}
            {...(trigger === "view"
              ? { whileInView: anim, viewport: { once: true, margin: "0px 0px -15% 0px" } }
              : { animate: anim })}
            transition={transition}
          />
        );
      })}
    </svg>
  );
}

